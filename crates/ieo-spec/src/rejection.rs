//! Correctable rejection responses (01-07): every rejection names a field
//! location and what to change. Codes are stable contract values.

use serde::Serialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Code {
    // --- format layer (HTTP 400) ---
    /// A required field is absent.
    MissingField,
    /// Any other JSON Schema violation (type, enum, pattern, conditional, extra field).
    SchemaViolation,
    // --- reference layer (HTTP 422) ---
    /// `digest` does not equal the canonical digest of the document.
    DigestMismatch,
    /// The same `task_id` appears twice in the spec.
    DuplicateTaskId,
    /// A prerequisite names a task that is neither in this spec nor registered (for that plan version).
    UndefinedPrerequisite,
    /// Prerequisites form a cycle.
    DependencyCycle,
    /// `acceptance.profile_id`/`profile_revision` is unknown, or an `item_id` is not in that profile.
    UnknownProfileItem,
    /// Executable registration was requested for a spec that is still `draft` / has unresolved bindings.
    UnboundDraft,
    // --- conflict (HTTP 409) ---
    /// Same `sprint_id` + `revision` already registered with a different digest,
    /// or a lower revision than the latest registered one.
    RevisionConflict,
    /// A `task_id` (submitted or generated by the converter) already belongs to another registered sprint (plan §1.6: ID conflict → 409).
    TaskIdConflict,
    // --- human input conversion (HTTP 400/422 at the conversion endpoint) ---
    /// A human `after` entry names no task in the input and no registered task ID.
    UnresolvedPrerequisite,
    /// Two human tasks share the same `name`.
    DuplicateTaskName,
    /// Estimate range with min > max (human `expected_duration` or spec `estimate.range_seconds`).
    EstimateRangeReversed,
    // --- API / report layer (01-08) ---
    /// Same Idempotency-Key with a different request body (HTTP 409).
    IdempotencyKeyConflict,
    /// Same (event_id, event_revision) with different content (HTTP 409).
    EventContentConflict,
    /// Report passes JSON Schema but breaks a rule the schema cannot express (HTTP 422).
    ReportSemanticViolation,
    /// Unknown or expired event cursor (HTTP 400).
    InvalidCursor,
}

impl Code {
    /// HTTP status the registration API (01-08 / plan §1.6) maps this code to.
    pub fn http_status(self) -> u16 {
        match self {
            Code::MissingField
            | Code::SchemaViolation
            | Code::DuplicateTaskName
            | Code::InvalidCursor => 400,
            Code::RevisionConflict
            | Code::TaskIdConflict
            | Code::IdempotencyKeyConflict
            | Code::EventContentConflict => 409,
            Code::DigestMismatch
            | Code::DuplicateTaskId
            | Code::UndefinedPrerequisite
            | Code::DependencyCycle
            | Code::UnknownProfileItem
            | Code::UnboundDraft
            | Code::UnresolvedPrerequisite
            | Code::EstimateRangeReversed
            | Code::ReportSemanticViolation => 422,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Rejection {
    pub code: Code,
    /// Location in the submitted document, e.g. `tasks[1].prerequisites[0].task_id`; `""` = whole document.
    pub field: String,
    pub message: String,
    pub correction: String,
    pub retryable_after_edit: bool,
}

impl Rejection {
    pub fn new(
        code: Code,
        field: impl Into<String>,
        message: impl Into<String>,
        correction: impl Into<String>,
    ) -> Self {
        Self {
            code,
            field: field.into(),
            message: message.into(),
            correction: correction.into(),
            // Every v0 rejection is fixable by editing the input; there is no
            // "retry unchanged" case at registration time.
            retryable_after_edit: true,
        }
    }
}

/// Convert a JSON Pointer (`/tasks/1/after/0`) to the dotted form used in responses (`tasks[1].after[0]`).
pub fn pointer_to_field(pointer: &str) -> String {
    let mut out = String::new();
    for seg in pointer.split('/').skip(1) {
        let seg = seg.replace("~1", "/").replace("~0", "~");
        if seg.chars().all(|c| c.is_ascii_digit()) && !seg.is_empty() {
            out.push_str(&format!("[{seg}]"));
        } else {
            if !out.is_empty() {
                out.push('.');
            }
            out.push_str(&seg);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pointer_conversion() {
        assert_eq!(pointer_to_field(""), "");
        assert_eq!(pointer_to_field("/tasks/1/after/0"), "tasks[1].after[0]");
        assert_eq!(pointer_to_field("/a~1b/c"), "a/b.c");
    }

    #[test]
    fn code_serializes_screaming() {
        let s = serde_json::to_string(&Code::UndefinedPrerequisite).unwrap_or_default();
        assert_eq!(s, "\"UNDEFINED_PREREQUISITE\"");
    }
}
